import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectDirectory = path.resolve(scriptDirectory, "..");
const canonicalSourcePath = path.join(
  projectDirectory,
  "data",
  "serrian-tide-skill-catalog.tsv",
);
const migrationPath = path.join(
  projectDirectory,
  "src-tauri",
  "migrations",
  "0003_seed_skill_catalog.sql",
);
const sourcePath = path.resolve(process.argv[2] ?? canonicalSourcePath);
const expectedHeaders = [
  "Primary Attribute",
  "Secondary Attribute",
  "Skill Type",
  "Skill Tier",
  "Skill Name",
  "Parent Skill",
  "Definition",
];
const emptyValues = new Set(["", "N/A", "—", "-", "None"]);

function sourceExternalId(name) {
  return `skill-${createHash("sha256")
    .update(name.toLocaleLowerCase("en-US"), "utf8")
    .digest("hex")}`;
}

function parseCatalog(source) {
  const lines = source.replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n").split("\n");
  if (!lines.at(-1)) lines.pop();
  const headers = lines.shift()?.split("\t").slice(0, expectedHeaders.length) ?? [];
  if (headers.join("\t") !== expectedHeaders.join("\t")) {
    throw new Error(
      `Unexpected catalog headers. Expected: ${expectedHeaders.join(", ")}`,
    );
  }

  const rows = lines.map((line, index) => {
    const columns = line.split("\t").slice(0, expectedHeaders.length);
    if (columns.length < expectedHeaders.length) {
      throw new Error(`Catalog row ${index + 2} has only ${columns.length} columns.`);
    }
    const [primary, secondary, classification, tierText, name, parent, definition] =
      columns.map((value) => value.trim());
    if (!name) throw new Error(`Catalog row ${index + 2} has no Skill Name.`);
    if (!classification) {
      throw new Error(`Catalog row ${index + 2} has no Skill Type.`);
    }
    if (!definition) {
      throw new Error(`Catalog row ${index + 2} has no Definition.`);
    }
    const tier = emptyValues.has(tierText) ? null : Number(tierText);
    if (tier !== null && (!Number.isInteger(tier) || tier < 1)) {
      throw new Error(`Catalog row ${index + 2} has invalid tier "${tierText}".`);
    }
    return {
      ordinal: index + 1,
      externalId: sourceExternalId(name),
      primaryAttribute: emptyValues.has(primary) ? null : primary,
      secondaryAttribute: emptyValues.has(secondary) ? null : secondary,
      classification,
      tier,
      name,
      parentName: emptyValues.has(parent) ? null : parent,
      definition,
    };
  });

  const names = new Map();
  for (const row of rows) {
    const key = row.name.toLocaleLowerCase("en-US");
    if (names.has(key)) {
      throw new Error(`Duplicate Skill Name "${row.name}".`);
    }
    names.set(key, row);
  }
  for (const row of rows) {
    if (
      row.parentName &&
      !names.has(row.parentName.toLocaleLowerCase("en-US"))
    ) {
      throw new Error(
        `Skill "${row.name}" references missing parent "${row.parentName}".`,
      );
    }
  }
  return rows;
}

function tsvValue(value) {
  const text = value ?? "N/A";
  if (/[\t\r\n]/u.test(text)) {
    throw new Error("Catalog fields cannot contain tabs or line breaks.");
  }
  return text;
}

function serializeCatalog(rows) {
  const body = rows.map((row) =>
    [
      row.primaryAttribute,
      row.secondaryAttribute,
      row.classification,
      row.tier,
      row.name,
      row.parentName,
      row.definition,
    ]
      .map(tsvValue)
      .join("\t"),
  );
  return `${expectedHeaders.join("\t")}\n${body.join("\n")}\n`;
}

function sqlValue(value) {
  if (value === null) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${value.replaceAll("'", "''")}'`;
}

function serializeMigration(rows, sourceHash) {
  const values = rows.map((row) =>
    `  (${[
      row.ordinal,
      row.externalId,
      row.name,
      row.classification,
      row.tier,
      row.primaryAttribute,
      row.secondaryAttribute,
      row.definition,
      row.parentName,
    ]
      .map(sqlValue)
      .join(", ")})`,
  );
  return `-- Generated by scripts/generate-skill-seed.mjs.
-- Canonical TSV SHA-256: ${sourceHash}
-- Do not hand-edit this migration; update the TSV and regenerate it.

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS temp._serrian_tide_skill_seed;
CREATE TEMP TABLE _serrian_tide_skill_seed (
    ordinal INTEGER PRIMARY KEY,
    source_external_id TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE,
    classification TEXT NOT NULL,
    tier INTEGER,
    primary_attribute TEXT,
    secondary_attribute TEXT,
    definition TEXT NOT NULL,
    parent_name TEXT COLLATE NOCASE
);

INSERT INTO _serrian_tide_skill_seed (
    ordinal,
    source_external_id,
    name,
    classification,
    tier,
    primary_attribute,
    secondary_attribute,
    definition,
    parent_name
) VALUES
${values.join(",\n")};

-- A source identity distinguishes canonical records from user-created Skills,
-- even when both intentionally use the same display name.
INSERT OR IGNORE INTO skills (
    name,
    classification,
    tier,
    primary_attribute,
    secondary_attribute,
    definition,
    created_by_user_id,
    source_system,
    source_external_id
)
SELECT
    name,
    classification,
    tier,
    primary_attribute,
    secondary_attribute,
    definition,
    NULL,
    'serrian-tide-core',
    source_external_id
FROM _serrian_tide_skill_seed
ORDER BY ordinal;

INSERT OR IGNORE INTO skill_relationships (
    skill_id,
    related_skill_id,
    relationship_type,
    sort_order
)
SELECT
    child.id,
    parent.id,
    'parent',
    0
FROM _serrian_tide_skill_seed child_seed
JOIN skills child
  ON child.source_system = 'serrian-tide-core'
 AND child.source_external_id = child_seed.source_external_id
JOIN _serrian_tide_skill_seed parent_seed
  ON parent_seed.name = child_seed.parent_name COLLATE NOCASE
JOIN skills parent
  ON parent.source_system = 'serrian-tide-core'
 AND parent.source_external_id = parent_seed.source_external_id
WHERE child_seed.parent_name IS NOT NULL;

DROP TABLE _serrian_tide_skill_seed;
`;
}

const source = await readFile(sourcePath, "utf8");
const rows = parseCatalog(source);
const canonicalSource = serializeCatalog(rows);
const sourceHash = createHash("sha256").update(canonicalSource).digest("hex");
const migration = serializeMigration(rows, sourceHash);

await mkdir(path.dirname(canonicalSourcePath), { recursive: true });
await mkdir(path.dirname(migrationPath), { recursive: true });
await Promise.all([
  writeFile(canonicalSourcePath, canonicalSource, "utf8"),
  writeFile(migrationPath, migration, "utf8"),
]);

const relationshipCount = rows.filter(({ parentName }) => parentName).length;
process.stdout.write(
  `Generated ${rows.length} Skills and ${relationshipCount} parent relationships.\n`,
);
